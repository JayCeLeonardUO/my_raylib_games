// Volumetric fog: ray-marched fBm noise, lit by up to 6 point lights through their shadow cubes, so
// casters leave dark shafts in the fog. One full-screen pass after the point-light shading. Each
// pixel's ray is marched from the camera to the scene depth (or maxDist); every step adds
// in-scattered light (ambient + each unshadowed light) and removes transmittance. Output is
// premultiplied: rgb = light scattered toward the camera, a = 1 - transmittance.
static const char* const VOLUMETRIC_FOG_FS =
    "#version 330\n"
    "in vec2 fragTexCoord;\n"
    "uniform sampler2D texture0;      // nearest linear view depth / zFar (RenderAPI::dof_depth)\n"
    "uniform samplerCube shadowCube0; // one shadow cube per light; GLSL 330 cannot index a sampler\n"
    "uniform samplerCube shadowCube1; // array with a loop variable, hence six names + cubeDist()\n"
    "uniform samplerCube shadowCube2;\n"
    "uniform samplerCube shadowCube3;\n"
    "uniform samplerCube shadowCube4;\n"
    "uniform samplerCube shadowCube5;\n"
    "uniform vec3 camPos;\n"
    "uniform vec3 camForward;\n"
    "uniform vec3 camRight;\n"
    "uniform vec3 camUp;\n"
    "uniform vec2 tanHalfFov;\n"
    "uniform float zFar;\n"
    "uniform float time;\n"
    "uniform int steps;\n"
    "uniform float density;\n"
    "uniform float maxDist;\n"
    "uniform float noiseScale;\n"
    "uniform float noiseAmount;       // 0 = even fog, 1 = full fBm clumps\n"
    "uniform float wind;\n"
    "uniform float fogTop;            // world y where the fog ends\n"
    "uniform float fogFade;           // world units over which it thins out below fogTop\n"
    "uniform vec3 ambient;            // light the fog has everywhere\n"
    "uniform float scatter;           // gain on point-light in-scattering\n"
    "uniform int lightCount;\n"
    "uniform vec3 lightPos[6];\n"
    "uniform vec3 lightColor;         // already times intensity\n"
    "uniform float radius;\n"
    "uniform float farPlane;\n"
    "uniform float bias;\n"
    "out vec4 finalColor;\n"
    "\n"
    "float hash(vec3 p) {\n"
    "  p = fract(p * 0.3183099 + 0.1);\n"
    "  p *= 17.0;\n"
    "  return fract(p.x * p.y * p.z * (p.x + p.y + p.z));\n"
    "}\n"
    "float noise(vec3 x) {\n"
    "  vec3 i = floor(x);\n"
    "  vec3 f = fract(x);\n"
    "  f = f * f * (3.0 - 2.0 * f);\n"
    "  return mix(mix(mix(hash(i), hash(i + vec3(1, 0, 0)), f.x),\n"
    "                 mix(hash(i + vec3(0, 1, 0)), hash(i + vec3(1, 1, 0)), f.x), f.y),\n"
    "             mix(mix(hash(i + vec3(0, 0, 1)), hash(i + vec3(1, 0, 1)), f.x),\n"
    "                 mix(hash(i + vec3(0, 1, 1)), hash(i + vec3(1, 1, 1)), f.x), f.y), f.z);\n"
    "}\n"
    "float fbm(vec3 p) {\n"
    "  float a = 0.5;\n"
    "  float s = 0.0;\n"
    "  for (int i = 0; i < 4; i++) {\n"
    "    s += a * noise(p);\n"
    "    p = p * 2.02 + vec3(13.1, 7.7, 3.3);\n"
    "    a *= 0.5;\n"
    "  }\n"
    "  return s;\n"
    "}\n"
    "float cubeDist(int i, vec3 v) {\n"
    "  if (i == 0) return texture(shadowCube0, v).r;\n"
    "  if (i == 1) return texture(shadowCube1, v).r;\n"
    "  if (i == 2) return texture(shadowCube2, v).r;\n"
    "  if (i == 3) return texture(shadowCube3, v).r;\n"
    "  if (i == 4) return texture(shadowCube4, v).r;\n"
    "  return texture(shadowCube5, v).r;\n"
    "}\n"
    "void main() {\n"
    "  float raw = texture(texture0, fragTexCoord).r;\n"
    "  vec2 ndc = fragTexCoord * 2.0 - 1.0;\n"
    "  // ray with 1 unit of view depth per unit of s, so s compares directly with the stored depth\n"
    "  vec3 ray = camForward + camRight * (ndc.x * tanHalfFov.x) + camUp * (ndc.y * tanHalfFov.y);\n"
    "  float rayLen = length(ray);\n"
    "  float sMax = min(raw >= 0.9999 ? maxDist : raw * zFar, maxDist); // stop at the scene\n"
    "  float ds = sMax / float(steps);\n"
    "  // per-pixel start offset: trades the banding of a fixed step for fine grain\n"
    "  float jitter = fract(52.9829189 * fract(dot(gl_FragCoord.xy, vec2(0.06711056, 0.00583715))));\n"
    "  vec3 drift = vec3(time * wind, 0.0, time * wind * 0.6);\n"
    "  float T = 1.0;          // how much of the scene behind still gets through\n"
    "  vec3 acc = vec3(0.0);   // light scattered toward the camera so far\n"
    "  for (int i = 0; i < 128; i++) {\n"
    "    if (i >= steps) break;\n"
    "    vec3 p = camPos + ray * ((float(i) + jitter) * ds);\n"
    "    float h = clamp((fogTop - p.y) / fogFade, 0.0, 1.0);\n"
    "    if (h <= 0.0) continue;\n"
    "    float n = fbm(p * noiseScale + drift);\n"
    "    float d = density * h * mix(1.0, smoothstep(0.25, 0.75, n) * 1.6, noiseAmount);\n"
    "    if (d <= 0.0005) continue;\n"
    "    vec3 light = ambient;\n"
    "    for (int k = 0; k < 6; k++) {\n"
    "      if (k >= lightCount) break;\n"
    "      vec3 v = p - lightPos[k];\n"
    "      float dl = length(v);\n"
    "      if (dl >= radius) continue;\n"
    "      if (dl > cubeDist(k, v) * farPlane + bias) continue;   // a caster is between light and fog: shaft\n"
    "      float a = 1.0 - dl / radius;\n"
    "      light += lightColor * (a * a) * scatter;\n"
    "    }\n"
    "    float stepT = exp(-d * ds * rayLen);\n"
    "    acc += T * (1.0 - stepT) * light;\n"
    "    T *= stepT;\n"
    "    if (T < 0.01) break;\n"
    "  }\n"
    "  finalColor = vec4(acc, 1.0 - T);\n"
    "}\n";
