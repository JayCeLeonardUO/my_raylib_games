// Point-light debug overlay, fragment: keeps only what the light reaches (inside the radius, facing
// the light, not behind a shadow caster in the cube) and outputs red with alpha = tint.
static const char* const POINT_LIGHT_DEBUG_FS =
    "#version 330\n"
    "in vec3 fragWorld;\n"
    "in vec3 fragNormal;\n"
    "uniform samplerCube shadowCube;\n"
    "uniform vec3 lightPos;\n"
    "uniform float farPlane;\n"
    "uniform float bias;\n"
    "uniform float radius;\n"
    "uniform float tint;\n"
    "out vec4 finalColor;\n"
    "void main() {\n"
    "  vec3 toFrag = fragWorld - lightPos;\n"
    "  float dist = length(toFrag);\n"
    "  if (dist >= radius) discard;                                // outside the effective radius\n"
    "  float nearest = texture(shadowCube, toFrag).r * farPlane;   // nearest caster in that direction\n"
    "  if (dist > nearest + bias) discard;                         // in shadow\n"
    "  finalColor = vec4(1.0, 0.0, 0.0, tint);                     // alpha-blended over the regular color\n"
    "}\n";

// Shadow cube preview: draws the six cube faces as a 3x2 sheet (+X -X +Y / -Y +Z -Z) through one
// samplerCube; grey = stored distance * scale, white = nothing there.
static const char* const SHADOW_PREVIEW_FS =
    "#version 330\n"
    "in vec2 fragTexCoord;\n"
    "uniform samplerCube shadowCube;\n"
    "uniform float scale;\n"
    "out vec4 finalColor;\n"
    "void main() {\n"
    "  vec2 g = fragTexCoord * vec2(3.0, 2.0);\n"
    "  int face = int(floor(g.x)) + 3 * int(floor(g.y));\n"
    "  vec2 p = fract(g) * 2.0 - 1.0;\n"
    "  vec3 d = face == 0 ? vec3(1.0, -p.y, -p.x) : face == 1 ? vec3(-1.0, -p.y, p.x)\n"
    "         : face == 2 ? vec3(p.x, 1.0, p.y) : face == 3 ? vec3(p.x, -1.0, -p.y)\n"
    "         : face == 4 ? vec3(p.x, -p.y, 1.0) : vec3(-p.x, -p.y, -1.0);\n"
    "  float v = texture(shadowCube, d).r;\n"
    "  finalColor = vec4(vec3(v >= 1.0 ? 1.0 : clamp(v * scale, 0.0, 1.0)), 1.0);\n"
    "}\n";

// G-buffer, vertex: same outputs as assets/shaders/three_point.vs (world position, uv, color,
// world normal, world tangent with handedness in w).
static const char* const GBUFFER_VS =
    "#version 330\n"
    "in vec3 vertexPosition;\n"
    "in vec2 vertexTexCoord;\n"
    "in vec3 vertexNormal;\n"
    "in vec4 vertexColor;\n"
    "in vec4 vertexTangent;\n"
    "uniform mat4 mvp;\n"
    "uniform mat4 matModel;\n"
    "uniform mat4 matNormal;\n"
    "out vec2 fragTexCoord;\n"
    "out vec4 fragColor;\n"
    "out vec3 fragNormal;\n"
    "out vec4 fragTangent;\n"
    "void main() {\n"
    "  fragTexCoord = vertexTexCoord;\n"
    "  fragColor = vertexColor;\n"
    "  fragNormal = normalize(vec3(matNormal * vec4(vertexNormal, 0.0)));\n"
    "  fragTangent = vec4(vec3(matModel * vec4(vertexTangent.xyz, 0.0)), vertexTangent.w);\n"
    "  gl_Position = mvp * vec4(vertexPosition, 1.0);\n"
    "}\n";

// G-buffer, fragment: target 0 = world normal * 0.5 + 0.5 with the normal map applied through the
// tangent frame (same code as three_point.fs), target 1 = surface color.
static const char* const GBUFFER_FS =
    "#version 330\n"
    "in vec2 fragTexCoord;\n"
    "in vec4 fragColor;\n"
    "in vec3 fragNormal;\n"
    "in vec4 fragTangent;\n"
    "uniform sampler2D texture0;\n"
    "uniform sampler2D texture2;   // tangent-space normal map (raylib binds MATERIAL_MAP_NORMAL here)\n"
    "uniform int useNormalMap;\n"
    "uniform vec4 colDiffuse;\n"
    "layout(location = 0) out vec4 outNormal;\n"
    "layout(location = 1) out vec4 outAlbedo;\n"
    "void main() {\n"
    "  vec3 N = normalize(fragNormal);\n"
    "  if (!gl_FrontFacing) N = -N;\n"
    "  if (useNormalMap == 1) {\n"
    "    vec3 T = normalize(fragTangent.xyz - N * dot(N, fragTangent.xyz));\n"
    "    vec3 B = cross(N, T) * fragTangent.w;\n"
    "    vec3 nm = texture(texture2, fragTexCoord).xyz * 2.0 - 1.0;\n"
    "    N = normalize(T * nm.x + B * nm.y + N * nm.z);\n"
    "  }\n"
    "  outNormal = vec4(N * 0.5 + 0.5, 1.0);\n"
    "  outAlbedo = vec4((texture(texture0, fragTexCoord) * colDiffuse * fragColor).rgb, 1.0);\n"
    "}\n";

// Point light, deferred shading: one full-screen pass added onto the finished frame. Rebuilds each
// pixel's world position from the main camera's depth, reads normal + surface color from the
// G-buffer and outputs diffuse + highlight, faded out by the radius and cut by the shadow cube.
static const char* const POINT_LIGHT_SHADE_FS =
    "#version 330\n"
    "in vec2 fragTexCoord;\n"
    "uniform sampler2D texture0;      // nearest linear view depth / zFar (RenderAPI::dof_depth)\n"
    "uniform sampler2D gDepth;        // G-buffer raw depth\n"
    "uniform samplerCube shadowCube;\n"
    "uniform vec3 camPos;\n"
    "uniform vec3 camForward;\n"
    "uniform vec3 camRight;\n"
    "uniform vec3 camUp;\n"
    "uniform vec2 tanHalfFov;         // (x, y): tan(fovy / 2) * aspect, tan(fovy / 2)\n"
    "uniform float zNear;\n"
    "uniform float zFar;\n"
    "uniform vec3 lightPos;\n"
    "uniform float farPlane;\n"
    "uniform float bias;\n"
    "uniform float radius;\n"
    "uniform sampler2D gNormal;\n"
    "uniform sampler2D gAlbedo;\n"
    "uniform vec3 lightColor;\n"
    "uniform float intensity;\n"
    "uniform float specStrength;\n"
    "uniform float specPower;\n"
    "out vec4 finalColor;\n"
    "void main() {\n"
    "  float raw = texture(texture0, fragTexCoord).r;\n"
    "  if (raw >= 0.9999) discard;                                  // nothing drawn at this pixel\n"
    "  // only pixels whose visible surface is in the G-buffer (ground + entities) are touched\n"
    "  float gd = texture(gDepth, fragTexCoord).r;\n"
    "  if (gd >= 1.0) discard;\n"
    "  float ndcz = gd * 2.0 - 1.0;\n"
    "  float gLin = (2.0 * zNear * zFar) / (zFar + zNear - ndcz * (zFar - zNear)) / zFar;\n"
    "  if (abs(gLin - raw) > 0.00002) discard;                      // something else is in front (a particle, ...)\n"
    "  // world position: walk the pixel's view ray until its depth along camForward is the stored one\n"
    "  vec2 ndc = fragTexCoord * 2.0 - 1.0;\n"
    "  vec3 ray = camForward + camRight * (ndc.x * tanHalfFov.x) + camUp * (ndc.y * tanHalfFov.y);\n"
    "  vec3 world = camPos + ray * (raw * zFar);\n"
    "  vec3 toL = lightPos - world;\n"
    "  float d = length(toL);\n"
    "  if (d >= radius) discard;\n"
    "  vec3 L = toL / d;\n"
    "  vec3 N = normalize(texture(gNormal, fragTexCoord).xyz * 2.0 - 1.0);\n"
    "  float nd = max(dot(N, L), 0.0);                              // how directly the surface faces the light\n"
    "  if (nd <= 0.0) discard;\n"
    "  float nearest = texture(shadowCube, -toL).r * farPlane;      // nearest caster in that direction\n"
    "  if (d > nearest + bias) discard;                             // in shadow\n"
    "  float a = 1.0 - d / radius;\n"
    "  float atten = a * a;                                         // fades to 0 at the radius\n"
    "  vec3 albedo = texture(gAlbedo, fragTexCoord).rgb;\n"
    "  vec3 H = normalize(L + normalize(camPos - world));\n"
    "  float spec = pow(max(dot(N, H), 0.0), specPower) * specStrength;\n"
    "  finalColor = vec4((albedo * nd + vec3(spec)) * lightColor * intensity * atten, 1.0);\n"
    "}\n";

