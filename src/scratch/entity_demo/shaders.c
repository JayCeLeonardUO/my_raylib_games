// GLSL sources for the point-light shadow capture in main.cpp (render section of update()).
// Included by main.cpp; written as GLSL 330, ShaderPortable swaps the header for the web build.
// Plain string literals so the file is valid as both C and C++.

// Shadow capture, vertex: passes the world position on.
static const char* const SHADOW_DIST_VS =
    "#version 330\n"
    "in vec3 vertexPosition;\n"
    "uniform mat4 mvp;\n"
    "uniform mat4 matModel;\n"
    "out vec3 fragWorld;\n"
    "void main() {\n"
    "  fragWorld = (matModel * vec4(vertexPosition, 1.0)).xyz;\n"
    "  gl_Position = mvp * vec4(vertexPosition, 1.0);\n"
    "}\n";

// Shadow capture, fragment: writes distance-to-light / farPlane into the cube face (1.0 = nothing there).
static const char* const SHADOW_DIST_FS =
    "#version 330\n"
    "in vec3 fragWorld;\n"
    "uniform vec3 lightPos;\n"
    "uniform float farPlane;\n"
    "out vec4 finalColor;\n"
    "void main() { finalColor = vec4(length(fragWorld - lightPos) / farPlane, 0.0, 0.0, 1.0); }\n";

